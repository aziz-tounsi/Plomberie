function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('plomb_lang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update Language Switcher UI Buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('bg-primary', 'text-white');
      btn.classList.remove('bg-white', 'text-slate-700', 'hover:bg-slate-100');
    } else {
      btn.classList.remove('bg-primary', 'text-white');
      btn.classList.add('bg-white', 'text-slate-700', 'hover:bg-slate-100');
    }
  });

  // Translate all text nodes with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Translate all placeholders with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update Custom Select Option Labels if rendered
  updateCustomSelectLabels(lang);
}

