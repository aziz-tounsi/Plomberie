// Custom Premium Dropdown Component (Rounded, sleek modern design replacing browser native selects)
function initCustomSelects() {
  const selectElements = document.querySelectorAll('select.custom-select-target');
  
  selectElements.forEach(select => {
    if (select.dataset.customized) return;
    select.dataset.customized = "true";
    select.style.display = 'none';

    const wrapper = document.createElement('div');
    const isPhoneCountry = select.id === 'phone-country';
    wrapper.className = `custom-select-wrapper ${isPhoneCountry ? 'phone-country-wrapper' : ''}`;

    const trigger = document.createElement('div');
    trigger.className = 'custom-select-trigger';

    const selectedOption = select.options[select.selectedIndex];
    const labelSpan = document.createElement('span');
    labelSpan.textContent = selectedOption ? selectedOption.textContent : (select.placeholder || 'Sélectionner...');

    const arrowIcon = document.createElement('span');
    arrowIcon.className = 'material-symbols-outlined text-slate-400 text-base transition-transform duration-200';
    arrowIcon.textContent = 'expand_more';

    trigger.appendChild(labelSpan);
    trigger.appendChild(arrowIcon);

    const optionsContainer = document.createElement('div');
    optionsContainer.className = 'custom-select-options';

    Array.from(select.options).forEach((opt, idx) => {
      if (idx === 0 && !opt.value && !isPhoneCountry) return; // Skip placeholder option for service select in list
      const optDiv = document.createElement('div');
      optDiv.className = `custom-option ${opt.selected ? 'selected' : ''}`;
      optDiv.textContent = opt.textContent;
      optDiv.dataset.value = opt.value;

      optDiv.addEventListener('click', (e) => {
        e.stopPropagation();
        select.value = opt.value;
        labelSpan.textContent = opt.textContent;
        
        optionsContainer.querySelectorAll('.custom-option').forEach(o => o.classList.remove('selected'));
        optDiv.classList.add('selected');

        wrapper.classList.remove('open');
        arrowIcon.style.transform = 'rotate(0deg)';

        select.dispatchEvent(new Event('change'));
      });

      optionsContainer.appendChild(optDiv);
    });

    trigger.addEventListener('click', (e) => {
      e.stopPropagation();
      document.querySelectorAll('.custom-select-wrapper.open').forEach(w => {
        if (w !== wrapper) {
          w.classList.remove('open');
          const icon = w.querySelector('.material-symbols-outlined');
          if (icon) icon.style.transform = 'rotate(0deg)';
        }
      });

      const isOpen = wrapper.classList.toggle('open');
      arrowIcon.style.transform = isOpen ? 'rotate(180deg)' : 'rotate(0deg)';
    });

    wrapper.appendChild(trigger);
    wrapper.appendChild(optionsContainer);
    select.parentNode.insertBefore(wrapper, select);
  });

  // Global click outside listener to close dropdowns
  document.addEventListener('click', () => {
    document.querySelectorAll('.custom-select-wrapper.open').forEach(w => {
      w.classList.remove('open');
      const icon = w.querySelector('.material-symbols-outlined');
      if (icon) icon.style.transform = 'rotate(0deg)';
    });
  });
}

// Belgian Postal Code & Commune Autocomplete
function initPostalCodeAutocomplete() {
  const postalInput = document.getElementById('postal-code');
  if (!postalInput) return;

  const parent = postalInput.parentNode;
  parent.style.position = 'relative';

  const suggestionBox = document.createElement('div');
  suggestionBox.className = 'autocomplete-suggestions hidden';
  parent.appendChild(suggestionBox);

  postalInput.addEventListener('input', (e) => {
    const val = e.target.value.toLowerCase().trim();
    suggestionBox.innerHTML = '';

    if (!val || val.length < 1) {
      suggestionBox.classList.add('hidden');
      return;
    }

    const matches = belgianLocations.filter(loc => loc.toLowerCase().includes(val)).slice(0, 6);

    if (matches.length === 0) {
      suggestionBox.classList.add('hidden');
      return;
    }

    matches.forEach(loc => {
      const item = document.createElement('div');
      item.className = 'suggestion-item';
      item.textContent = loc;

      item.addEventListener('click', () => {
        postalInput.value = loc;
        suggestionBox.classList.add('hidden');
      });

      suggestionBox.appendChild(item);
    });

    suggestionBox.classList.remove('hidden');
  });

  // Close on outside click
  document.addEventListener('click', (e) => {
    if (e.target !== postalInput && !suggestionBox.contains(e.target)) {
      suggestionBox.classList.add('hidden');
    }
  });
}

function getPhoneRule(code) {
  return countryPhoneRules[code] || { minLength: 8, maxLength: 12, name: "Internationaal", placeholder: "Telefoonnummer" };
}

function updatePhoneInputConstraints() {
  const phoneInput = document.getElementById('phone-number');
  const countrySelect = document.getElementById('phone-country');
  if (!phoneInput || !countrySelect) return;

  const code = countrySelect.value || '+32';
  const rule = getPhoneRule(code);

  phoneInput.placeholder = rule.placeholder;
  phoneInput.maxLength = rule.maxLength;
}

function validatePhoneNumber() {
  const phoneInput = document.getElementById('phone-number');
  const countrySelect = document.getElementById('phone-country');
  if (!phoneInput || !countrySelect) return true;

  const code = countrySelect.value || '+32';
  const digits = phoneInput.value.replace(/[^0-9]/g, '');
  const rule = getPhoneRule(code);

  if (rule.minLength === rule.maxLength) {
    if (digits.length !== rule.minLength) {
      const msg = currentLang === 'nl'
        ? `❌ Ongeldig telefoonnummer voor ${code} (${rule.name}). Voer exact ${rule.minLength} cijfers in. (U heeft ${digits.length} cijfers ingevoerd)`
        : `❌ Numéro de téléphone invalide pour ${code} (${rule.name}). Veuillez entrer exactement ${rule.minLength} chiffres. (Vous avez entré ${digits.length} chiffres)`;
      alert(msg);
      phoneInput.classList.add('border-red-500', 'ring-2', 'ring-red-300');
      phoneInput.focus();
      return false;
    }
  } else {
    if (digits.length < rule.minLength || digits.length > rule.maxLength) {
      const msg = currentLang === 'nl'
        ? `❌ Ongeldig telefoonnummer voor ${code} (${rule.name}). Voer tussen ${rule.minLength} en ${rule.maxLength} cijfers in. (U heeft ${digits.length} cijfers ingevoerd)`
        : `❌ Numéro de téléphone invalide pour ${code} (${rule.name}). Veuillez entrer entre ${rule.minLength} et ${rule.maxLength} chiffres. (Vous avez entré ${digits.length} chiffres)`;
      alert(msg);
      phoneInput.classList.add('border-red-500', 'ring-2', 'ring-red-300');
      phoneInput.focus();
      return false;
    }
  }

  phoneInput.classList.remove('border-red-500', 'ring-2', 'ring-red-300');
  return true;
}

// Telephone Input Digit Filtering & Country Selector
function initPhoneInput() {
  const phoneInput = document.getElementById('phone-number');
  const countrySelect = document.getElementById('phone-country');
  if (!phoneInput) return;

  updatePhoneInputConstraints();

  phoneInput.addEventListener('input', (e) => {
    const code = countrySelect ? countrySelect.value : '+32';
    const rule = getPhoneRule(code);
    let cleanVal = e.target.value.replace(/[^0-9]/g, '');
    if (cleanVal.length > rule.maxLength) {
      cleanVal = cleanVal.slice(0, rule.maxLength);
    }
    e.target.value = cleanVal;
    if (cleanVal.length === rule.minLength) {
      phoneInput.classList.remove('border-red-500', 'ring-2', 'ring-red-300');
    }
  });

  if (countrySelect) {
    countrySelect.addEventListener('change', () => {
      updatePhoneInputConstraints();
      phoneInput.focus();
    });
  }
}

// Interactive Services Carousel Slider
function initServicesCarousel() {
  const container = document.getElementById('services-carousel');
  if (!container) return;

  const slides = container.querySelectorAll('.carousel-slide');
  const prevBtn = document.getElementById('carousel-prev');
  const nextBtn = document.getElementById('carousel-next');
  const dotsContainer = document.getElementById('carousel-dots');

  if (!slides || slides.length === 0) return;

  let currentIndex = 0;
  let autoTimer = null;

  if (dotsContainer) {
    dotsContainer.innerHTML = '';
    slides.forEach((_, idx) => {
      const dot = document.createElement('button');
      dot.className = `w-2.5 h-2.5 rounded-full transition-all duration-300 ${idx === 0 ? 'bg-primary w-7' : 'bg-slate-300 hover:bg-slate-400'}`;
      dot.setAttribute('aria-label', `Slide ${idx + 1}`);
      dot.addEventListener('click', () => {
        goToSlide(idx);
        resetAutoTimer();
      });
      dotsContainer.appendChild(dot);
    });
  }

  function updateDots() {
    if (!dotsContainer) return;
    const dots = dotsContainer.querySelectorAll('button');
    dots.forEach((dot, idx) => {
      if (idx === currentIndex) {
        dot.className = 'w-7 h-2.5 rounded-full bg-primary transition-all duration-300';
      } else {
        dot.className = 'w-2.5 h-2.5 rounded-full bg-slate-300 hover:bg-slate-400 transition-all duration-300';
      }
    });
  }

  function goToSlide(index) {
    slides[currentIndex].classList.add('hidden');
    slides[currentIndex].classList.remove('block');

    currentIndex = (index + slides.length) % slides.length;

    slides[currentIndex].classList.remove('hidden');
    slides[currentIndex].classList.add('block');

    updateDots();
  }

  function nextSlide() {
    goToSlide(currentIndex + 1);
  }

  function prevSlide() {
    goToSlide(currentIndex - 1);
  }

  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      nextSlide();
      resetAutoTimer();
    });
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      prevSlide();
      resetAutoTimer();
    });
  }

  // Swipe Gestures Support for Mobile
  let startX = 0;
  container.addEventListener('touchstart', (e) => {
    startX = e.touches[0].clientX;
  }, { passive: true });

  container.addEventListener('touchend', (e) => {
    const endX = e.changedTouches[0].clientX;
    const diffX = startX - endX;
    if (Math.abs(diffX) > 40) {
      if (diffX > 0) nextSlide();
      else prevSlide();
      resetAutoTimer();
    }
  }, { passive: true });

  function startAutoTimer() {
    autoTimer = setInterval(nextSlide, 5000);
  }

  function resetAutoTimer() {
    if (autoTimer) clearInterval(autoTimer);
    startAutoTimer();
  }

  startAutoTimer();
}

