// Floating Action Bar on Scroll
function initScrollIsland() {
  const island = document.getElementById('floating-island');
  if (!island) return;

  window.addEventListener('scroll', () => {
    if (window.scrollY > 250) {
      island.classList.remove('opacity-0', 'translate-y-10');
      island.classList.add('opacity-100', 'translate-y-0');
    } else {
      island.classList.add('opacity-0', 'translate-y-10');
      island.classList.remove('opacity-100', 'translate-y-0');
    }
  });
}

// Zones Interactivity: Search Filter & Commune Tag Clicking
function initZonesInteractivity() {
  const searchInput = document.getElementById('commune-search-input');
  const communeTags = document.querySelectorAll('.commune-tag');

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      const val = e.target.value.toLowerCase().trim();
      communeTags.forEach(tag => {
        const text = tag.textContent.toLowerCase();
        if (text.includes(val)) {
          tag.style.display = 'inline-flex';
        } else {
          tag.style.display = 'none';
        }
      });
    });
  }

  communeTags.forEach(tag => {
    tag.style.cursor = 'pointer';
    tag.title = 'Klik om een offerte aan te vragen voor deze gemeente / Cliquez pour demander un devis';
    tag.addEventListener('click', () => {
      const communeName = tag.textContent.trim();
      window.location.href = `devis.html?commune=${encodeURIComponent(communeName)}`;
    });
  });
}

// Check URL Params for prefilling fields
function checkUrlParams() {
  const params = new URLSearchParams(window.location.search);
  const commune = params.get('commune');
  if (commune) {
    const postalInput = document.getElementById('postal-code');
    if (postalInput) {
      postalInput.value = commune;
      postalInput.focus();
    }
  }
}
